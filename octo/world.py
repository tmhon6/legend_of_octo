    if not _FLAT_SHADE:
        s_ = pygame.Surface((TILE, TILE), pygame.SRCALPHA)
        s_.fill((0, 0, 20, 70))
        _FLAT_SHADE.append(s_)
    return _FLAT_SHADE[0]


