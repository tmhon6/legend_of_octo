OPENABLE = set('KLRIlBU')       # tiles that can be opened for good (saved in savegames)
FLOOR_CHARS = set('.,=dH')


def in_rect(tx, ty, r):
    return r[0] <= tx <= r[2] and r[1] <= ty <= r[3]


def area_at(tx, ty):
    if ty >= CITY_Y:
        return 'overworld'
    if ty >= TEMPLE_Y:
        return 'dungeon'
    if in_rect(tx, ty, SKY_RECT):
        return 'sky'
    if WORLD_H <= ty < SKY_Y:
        return 'trial'
    return 'dungeon' if in_rect(tx, ty, SHRINE_RECT) else 'overworld'


def trial_at(tx, ty):
    for name, t in TRIALS.items():
        if in_rect(tx, ty, t['room']):
            return name
    return None


def temple_at(tx, ty):
    if ty < TEMPLE_Y:
        return None
    for tid, t in TEMPLES.items():
        if in_rect(tx, ty, t['rect']):
            return tid
    return None


def city_at(tx, ty):
    if ty < CITY_Y:
        return None
    for cid, c in CITIES.items():
        if in_rect(tx, ty, c['rect']):
            return cid
    return None


def city_door(tx, ty):
    for cid, c in CITIES.items():
        if c['door'] == (tx, ty):
            return cid
    return None


def temple_door(tx, ty):
    for tid, t in TEMPLES.items():
        if t['door'] == (tx, ty):
            return tid
    return None


_REGION_GRID = None


def _region_grid():
    """Which region every tile is in, painted once (the first region listed wins)."""
    global _REGION_GRID
    grid = [[None] * LEVEL_W for _ in range(TEMPLE_Y)]
    defaults = {'sky': 'SKY ISLANDS', 'land': 'THE SURFACE', 'under': 'THE UNDERDEEP'}
    for wld, (x0, y0, x1, y1) in WORLD_RECTS.items():
        if wld in defaults:
            for y in range(y0, min(y1 + 1, TEMPLE_Y)):
                grid[y][x0:x1 + 1] = [defaults[wld]] * (x1 - x0 + 1)
    for name, (x0, y0, x1, y1) in reversed(REGIONS):
        for y in range(max(0, y0), min(y1 + 1, TEMPLE_Y)):
            grid[y][x0:x1 + 1] = [name] * (x1 - x0 + 1)
    _REGION_GRID = grid
    return grid


def region_at(tx, ty):
    if ty >= CITY_Y:
        cid = city_at(tx, ty)
        return CITIES[cid]['title'] if cid else 'CORAL REEF'
    if ty >= TEMPLE_Y:
        tid = temple_at(tx, ty)
        return TEMPLES[tid]['title'] if tid else 'CORAL REEF'
    g = _REGION_GRID or _region_grid()
    if 0 <= ty < TEMPLE_Y and 0 <= tx < LEVEL_W:
        return g[ty][tx] or 'CORAL REEF'
    return 'CORAL REEF'


def world_at(tx, ty):
    """'sea', 'sky', 'land' or 'under' -- or None in the trial rooms, temples and the boss lair."""
    for wld, r in WORLD_RECTS.items():
        if in_rect(tx, ty, r):
            return wld
    return None


def theme_at(tx, ty):
    return THEMES.get(region_at(tx, ty), 'reef')


def floor_for(tx, ty):
    return '=' if area_at(tx, ty) in ('dungeon', 'trial') else '.'


def arena_tile_rect(a):
    x0, y0, x1, y1 = a['rect']
    return pygame.Rect(x0 * TILE, y0 * TILE, (x1 - x0 + 1) * TILE, (y1 - y0 + 1) * TILE)


def arena_of(tx, ty):
    for name, a in ARENAS.items():
        x0, y0, x1, y1 = a['rect']
        if x0 <= tx <= x1 and y0 <= ty <= y1:
            return name
    return None


class Level:
    def __init__(self, opened=()):
        self.w, self.h = LEVEL_W, LEVEL_H
        self.px_w, self.px_h = self.w * TILE, self.h * TILE
        self.bounds = pygame.Rect(0, 0, self.px_w, self.px_h)
        self.tiles = [list(r) for r in LEVEL]
        # shutters start open: remember where they are, per arena
        self.doors = {name: [] for name in ARENAS}
        for y in range(self.h):
            for x in range(self.w):
                if self.tiles[y][x] == 'X':
                    self.tiles[y][x] = '='
                    for name, a in ARENAS.items():
                        x0, y0, x1, y1 = a['rect']
                        if x0 - 1 <= x <= x1 + 1 and y0 - 1 <= y <= y1 + 1:
                            self.doors[name].append((x, y))
        for (tx, ty) in opened:
            self.tiles[ty][tx] = floor_for(tx, ty)
        self.blockers = []
        self.ghost_ok = False          # True while Octo is in Spooky form
        self.hover_ok = False          # Cloudy floats over pits, ponds and sky gaps
        self.lava_ok = False           # Magmy walks on lava
        self.themes = [[theme_at(x, y) for x in range(self.w)] for y in range(self.h)]
        self.surface = None
        self.chunks = {}
        self.dirty_tiles = set()

    # -- tiles -------------------------------------------------------------
    def tile(self, tx, ty):
        if 0 <= tx < self.w and 0 <= ty < self.h:
            return self.tiles[ty][tx]
        return None

    def set_tile(self, tx, ty, ch):
        self.tiles[ty][tx] = ch
        self.dirty_tiles.add((tx, ty))

    def set_doors(self, arena, closed):
        for (tx, ty) in self.doors[arena]:
            self.set_tile(tx, ty, 'X' if closed else '=')

    def solid(self, ch, who):
        if ch is None or ch in SOLID_ALL or ch == 'X':
            return True
        if ch in 'vl':
            if who == 'player' and ((ch == 'v' and self.hover_ok) or (ch == 'l' and self.lava_ok)):
                return False
            return who in ('player', 'walker')
        if ch == 'G':
            return not (who == 'player' and self.ghost_ok)
        return False

    def tiles_in(self, rect):
        x0, x1 = rect.left // TILE, (rect.right - 1) // TILE
        y0, y1 = rect.top // TILE, (rect.bottom - 1) // TILE
        for ty in range(y0, y1 + 1):
            for tx in range(x0, x1 + 1):
                yield tx, ty, self.tile(tx, ty)

    def blocked(self, rect, who):
        if not self.bounds.contains(rect):
            return True
        for tx, ty, ch in self.tiles_in(rect):
            if self.solid(ch, who):
                return True
        if who != 'shot':
            for b in self.blockers:
                if rect.colliderect(b):
                    return True
        return False

    def flood(self, tx, ty, ch):
        """All tiles of type ch connected to (tx, ty)."""
        out, todo = set(), [(tx, ty)]
        while todo:
            x, y = todo.pop()
            if (x, y) in out or self.tile(x, y) != ch:
                continue
            out.add((x, y))
            todo += [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]
        return out

    # -- drawing -----------------------------------------------------------
    PYRAMID_HEIGHT = {'P': 1, 'Q': 2, 'H': 1}

    def _height(self, tx, ty):
        ch = self.tile(tx, ty)
        if ch == '=' and region_at(tx, ty) == 'OCTO TEMPLE':
            return 3                     # the sanctuary on top
        return self.PYRAMID_HEIGHT.get(ch, 0)

    def _blit_tile(self, tiles, tx, ty, surf=None, off=(0, 0)):
        surf = surf or self.surface
        ch = self.tiles[ty][tx]
        if (tx, ty) in _props3d.FLAT:       # a 3D building stands here: just the ground under it
            themed = tiles['themes'].get(self.themes[ty][tx], {}) if area_at(tx, ty) == 'overworld' else {}
            floor = themed.get('.') or tiles['overworld']['.']
            pos = (tx * TILE - off[0], ty * TILE - off[1])
            surf.blit(floor[(tx * 7 + ty * 13) % len(floor)], pos)
            if (tx, ty) not in _props3d.NOSHADE:
                surf.blit(_flat_shade(), pos)
            return
        top = ch == '=' and region_at(tx, ty) == 'OCTO TEMPLE'
        if ch in 'PQH' or top:
            h = self._height(tx, ty)
            lower = tuple(self._height(tx + dx, ty + dy) < h for dx, dy in ((0, -1), (0, 1), (-1, 0), (1, 0)))
            rail = (self.tile(tx - 1, ty) != 'H', self.tile(tx + 1, ty) != 'H')
            surf.blit(gfx.pyramid_tile('T' if top else ch, lower, rail), (tx * TILE - off[0], ty * TILE - off[1]))
            return
        area = 'dungeon' if area_at(tx, ty) in ('dungeon', 'trial') else 'overworld'
        other = 'overworld' if area == 'dungeon' else 'dungeon'
        themed = tiles['themes'].get(self.themes[ty][tx], {}) if area == 'overworld' else {}
        variants = themed.get(ch) or tiles[area].get(ch) or tiles[other].get(ch) or tiles[area][floor_for(tx, ty)]
        img = variants[(tx * 7 + ty * 13 + tx * ty) % len(variants)]
        surf.blit(img, (tx * TILE - off[0], ty * TILE - off[1]))

    CHUNK = 32          # tiles per side of a cached piece of the map
    MAX_CHUNKS = 16

    def _chunk(self, tiles, key):
        c = self.CHUNK
        surf = pygame.Surface((c * TILE, c * TILE))
        off = (key[0] * c * TILE, key[1] * c * TILE)
        for ty in range(key[1] * c, min(self.h, key[1] * c + c)):
            for tx in range(key[0] * c, min(self.w, key[0] * c + c)):
                self._blit_tile(tiles, tx, ty, surf, off)
        return surf

    def draw_view(self, dest, tiles, view):
        """Blit the part of the map under the camera. The map is drawn in chunks on demand,
        so the whole (tall) map never has to sit in memory at once."""
        c = self.CHUNK
        if self.dirty_tiles:
            for (tx, ty) in self.dirty_tiles:
                key = (tx // c, ty // c)
                if key in self.chunks:
                    self._blit_tile(tiles, tx, ty, self.chunks[key], (key[0] * c * TILE, key[1] * c * TILE))
            self.dirty_tiles.clear()
        span = c * TILE
        for cy in range(max(0, view.top // span), (view.bottom - 1) // span + 1):
            for cx in range(max(0, view.left // span), (view.right - 1) // span + 1):
                if cx * c >= self.w or cy * c >= self.h:
                    continue
                key = (cx, cy)
                surf = self.chunks.pop(key, None) or self._chunk(tiles, key)
                self.chunks[key] = surf              # most recently used last
                dest.blit(surf, (cx * span - view.x, cy * span - view.y))
        while len(self.chunks) > self.MAX_CHUNKS:
            del self.chunks[next(iter(self.chunks))]

    def render(self, tiles):
        if self.surface is None:
            self.surface = pygame.Surface((self.px_w, self.px_h))
            for ty in range(self.h):
                for tx in range(self.w):
                    self._blit_tile(tiles, tx, ty)
            self.dirty_tiles.clear()
        for (tx, ty) in self.dirty_tiles:
            self._blit_tile(tiles, tx, ty)
        self.dirty_tiles.clear()
        return self.surface


def validate():
    problems = []
    for i, row in enumerate(LEVEL):
        if len(row) != LEVEL_W:
            problems.append(f"row {i} has {len(row)} tiles, expected {LEVEL_W}")
    if problems:
        return problems
    for kind, tx, ty in ENEMIES + ITEMS:
        if LEVEL[int(ty)][int(tx)] not in FLOOR_CHARS:
            problems.append(f"{kind} at {(tx, ty)} sits on {LEVEL[int(ty)][int(tx)]!r}")
    for name, a in ARENAS.items():
        kind, tx, ty = a['reward']
        if LEVEL[int(ty)][int(tx)] not in FLOOR_CHARS:
            problems.append(f"{name} reward sits on {LEVEL[int(ty)][int(tx)]!r}")
    # can Octo reach everything? (kelp can be cut, doors unlocked, shutters open)
    walk = FLOOR_CHARS | set('KLXRIGlYEBUAD')
    links = {}
    for a, b in GEYSERS:
        links[a] = b
        links[b] = a     # R: cracked rock, bombs open it
    for a, b, _kind in PASSAGES:
        links[a] = b
        links[b] = a
    for c in CITIES.values():
        inside = (int(c['entry'][0]), int(c['entry'][1]))
        links[c['door']] = inside
        links[inside] = c['door']
        if LEVEL[c['door'][1]][c['door'][0]] != 'E':
            problems.append(f"{c['id']} gate at {c['door']} is not an E tile")
        for who, (x, y) in c['spots'].items():
            if LEVEL[int(y)][int(x)] not in FLOOR_CHARS:
                problems.append(f"{c['id']}: {who} stands on {LEVEL[int(y)][int(x)]!r} at {(x, y)}")
    for t in TEMPLES.values():
        inside = (int(t['entry'][0]), int(t['entry'][1]))
        links[t['door']] = inside
        links[inside] = t['door']
        if LEVEL[t['door'][1]][t['door'][0]] != 'E':
            problems.append(f"{t['id']} door at {t['door']} is not an E tile")
    seen = {(int(START[0]), int(START[1]))}
    q = deque(seen)
    while q:
        x, y = q.popleft()
        hops = [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)] + ([links[(x, y)]] if (x, y) in links else [])
        for nx, ny in hops:
            if 0 <= nx < LEVEL_W and 0 <= ny < LEVEL_H and (nx, ny) not in seen \
                    and LEVEL[ny][nx] in walk:
                seen.add((nx, ny))
                q.append((nx, ny))
    import folk
    targets = [(k, x, y) for k, x, y in ENEMIES + ITEMS] + \
              [(n, a['reward'][1], a['reward'][2]) for n, a in ARENAS.items()]
    targets += [('quest ' + q, x, y) for q, spots in folk.QUEST_SPOTS.items() for x, y in spots]
    targets += [(c['id'] + ' ' + who, x, y) for c in CITIES.values() for who, (x, y) in c['spots'].items()]
    for q, spots in folk.QUEST_SPOTS.items():
        for x, y in spots:
            if LEVEL[y][x] not in FLOOR_CHARS:
                problems.append(f"quest {q} item at {(x, y)} sits on {LEVEL[y][x]!r}")
    for name, t in TRIALS.items():
        px, py = t['portal']
        targets += [(name + ' portal', px, py), (name + ' portal exit', px, py + 1)]
    for k, x, y in targets:
        if (int(x), int(y)) not in seen:
            problems.append(f"{k} at {(x, y)} is unreachable")
    # each trial room: everything inside must be on floor and reachable from where Octo lands
    for name, t in TRIALS.items():
        x0, y0 = t['room'][:2]
        ex, ey = int(t['entry'][0]) + x0, int(t['entry'][1]) + y0
        inside = {(ex, ey)}
        q = deque(inside)
        while q:
            x, y = q.popleft()
            for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
                if (nx, ny) not in inside and LEVEL[ny][nx] in FLOOR_CHARS:
                    inside.add((nx, ny))
                    q.append((nx, ny))
        pts = [('entry', *t['entry'])] + [('orb', x, y) for x, y in t.get('orbs', [])] + \
              [(k, x, y) for k, x, y in t.get('guards', [])] + [('spot', x, y) for x, y in t.get('spots', [])] + \
              [(k, *t[k]) for k in ('boss_at', 'thief_at', 'clam_at') if k in t] + \
              ([('flag', *t['goal'])] if t['kind'] == 'race' else []) + \
              [('sentry', x, y) for x, y in t.get('sentries', [])]
        for k, x, y in pts:
            if (int(x) + x0, int(y) + y0) not in inside:
                problems.append(f"{name}: {k} at {(x, y)} is not reachable floor")
            elif x != int(x) and k in ('entry', 'boss_at', 'thief_at', 'clam_at') and \
                    (int(x) + 1 + x0, int(y) + y0) not in inside:
                problems.append(f"{name}: {k} at {(x, y)} overlaps a wall")
    return problems


_FLAT_SHADE = []


